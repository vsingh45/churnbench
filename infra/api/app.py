"""ChurnBench mock SaaS API.

Deliberately imperfect: adds latency and enforces a per-minute rate limit,
so naive tool-calling (arm 1) pays a real price for hitting it live per query.
Reads from MongoDB — data is generated by churnbench/generator.
"""
from __future__ import annotations

import asyncio
import os
import time
from collections import deque

from fastapi import FastAPI, HTTPException
from pymongo import MongoClient

LATENCY_MS = int(os.getenv("SAAS_LATENCY_MS", "350"))
RATE_LIMIT_PER_MIN = int(os.getenv("SAAS_RATE_LIMIT_PER_MIN", "60"))

app = FastAPI(title="ChurnBench Mock SaaS")
_client = MongoClient("mongodb://mongodb:27017/")
_db = _client["sam_ops"]

_call_log: deque[float] = deque()


def _rate_limit() -> None:
    """Sliding-window rate limit; raises 429 when exceeded."""
    now = time.time()
    while _call_log and now - _call_log[0] > 60:
        _call_log.popleft()
    if len(_call_log) >= RATE_LIMIT_PER_MIN:
        raise HTTPException(status_code=429, detail="rate limit exceeded")
    _call_log.append(now)


async def _throttle() -> None:
    _rate_limit()
    await asyncio.sleep(LATENCY_MS / 1000)


@app.get("/health")
async def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/entitlements/{user_ext_id}")
async def get_entitlements(user_ext_id: str) -> dict:
    """SaaS view of what a user is entitled to right now."""
    await _throttle()
    doc = _db["entitlements"].find_one({"user_ext_id": user_ext_id}, {"_id": 0})
    if not doc:
        raise HTTPException(status_code=404, detail="user not found")
    return doc


@app.get("/tickets")
async def list_tickets(status: str | None = None, product_sku: str | None = None) -> list[dict]:
    """SaaS ticket list — the 'complaints, requests, offboardings' stream."""
    await _throttle()
    q: dict = {}
    if status:
        q["status"] = status
    if product_sku:
        q["product_sku"] = product_sku
    return list(_db["tickets"].find(q, {"_id": 0}).limit(200))


@app.get("/products/{product_sku}/current-utilization")
async def current_utilization(product_sku: str) -> dict:
    """Current live utilization view — the query that most tempts naive tool-calls."""
    await _throttle()
    doc = _db["utilization_current"].find_one({"product_sku": product_sku}, {"_id": 0})
    if not doc:
        raise HTTPException(status_code=404, detail="product not found")
    return doc
